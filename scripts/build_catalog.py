"""Regenerate ``adspirer_catalog.py`` from the Adspirer REST API's OpenAPI document.

Usage: python scripts/build_catalog.py path/to/openapi.json

The catalog records, for every tool, whether the API marks it read-only or destructive. The Run Tool
component uses it to refuse changes unless the flow author has switched them on.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src/lfx_adspirer/components/adspirer/adspirer_catalog.py"
PREFIX, SUFFIX = "/api/v1/tools/", "/execute"
# The API reference documents these as read-only diagnostics that never use the tool-call
# allowance, but the OpenAPI document does not flag them read-only.
READ_ONLY_OVERRIDES = {"get_connections_status", "list_connected_accounts"}


def main(spec_path: str) -> None:
    spec = json.loads(Path(spec_path).read_text(encoding="utf-8"))
    read_only, destructive, changes = [], [], []
    for path, item in spec["paths"].items():
        if not (path.startswith(PREFIX) and path.endswith(SUFFIX)):
            continue
        tool = path[len(PREFIX) : -len(SUFFIX)]
        operation = item["post"]
        if operation.get("x-adspirer-destructive"):
            destructive.append(tool)
        elif operation.get("x-adspirer-read-only") or tool in READ_ONLY_OVERRIDES:
            read_only.append(tool)
        else:
            changes.append(tool)

    def block(name: str, tools: list[str]) -> str:
        rows = "".join(f'        "{tool}",\n' for tool in sorted(tools))
        return f"{name}: frozenset[str] = frozenset(\n    {{\n{rows}    }}\n)\n"

    OUT.write_text(
        '"""Adspirer tool catalog: which tools read, which change an ad account, which delete.\n\n'
        "Generated by scripts/build_catalog.py from the Adspirer REST API's OpenAPI document\n"
        "(the ``x-adspirer-read-only`` and ``x-adspirer-destructive`` flags). Do not edit by hand.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        + block("READ_ONLY_TOOLS", read_only)
        + "\n"
        + block("CHANGE_TOOLS", changes)
        + "\n"
        + block("DESTRUCTIVE_TOOLS", destructive),
        encoding="utf-8",
    )
    print(f"{len(read_only)} read-only, {len(changes)} change, {len(destructive)} destructive -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
